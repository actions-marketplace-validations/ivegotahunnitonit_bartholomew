def detect_workspace_stack(root_path: str = ".") -> Dict[str, Any]:
    """
    Scans the workspace to identify active tools, extensions, and configurations.
    """
    root = Path(root_path).resolve()
    detected_tools = []
    detected_agents = []
    config_files = []

    # Check for IDE configs
    vscode_dir = root / ".vscode"
    if vscode_dir.exists():
        ext_json = vscode_dir / "extensions.json"
        if ext_json.exists():
            try:
                data = json.loads(ext_json.read_text(encoding="utf-8"))
                recs = data.get("recommendations", [])
                detected_tools.extend(recs)
            except Exception:
                pass
        config_files.append(".vscode")

    # Check for Cursor / Claude / Gemini rules
    if (root / ".cursorrules").exists() or (root / ".cursor").exists():
        detected_agents.append("Cursor AI")
        config_files.append(".cursorrules")
    if (root / "CLAUDE.md").exists():
        detected_agents.append("Claude Code / Anthropic")
        config_files.append("CLAUDE.md")
    if (root / "GEMINI.md").exists():
        detected_agents.append("Google Gemini")
        config_files.append("GEMINI.md")
    if (root / "llms.txt").exists():
        config_files.append("llms.txt")

    # Check for Linters and Formatters
    if any(root.glob(".eslintrc*")) or (root / "eslint.config.js").exists():
        detected_tools.append("ESLint")
    if any(root.glob(".prettierrc*")):
        detected_tools.append("Prettier")
    if (root / "ruff.toml").exists() or (root / "pyproject.toml").exists():
        detected_tools.append("Ruff / Pytest")
    if (root / "Dockerfile").exists() or (root / "docker-compose.yml").exists():
        detected_tools.append("Docker")
    if (root / ".git").exists():
        detected_tools.append("Git")

    return {
        "workspace_root": str(root),
        "detected_agents": detected_agents or ["Universal AI Coding Assistants"],
        "detected_tools": detected_tools or ["Standard Toolchain"],
        "config_files": config_files
    }


def calculate_savings_telemetry(root_path: str = ".") -> Dict[str, Any]:
    """
    Calculates estimated token and dollar savings enabled by Bartholomew's
    deterministic circuit breakers and AST caching.
    """
    root = Path(root_path).resolve()
    audit_file = root / ".btp" / "audit.log"
    total_evals = 0
    total_blocked = 0

    if audit_file.exists():
        try:
            with open(audit_file, "r", encoding="utf-8") as f:
                for line in f:
                    if line.strip():
                        total_evals += 1
                        try:
                            ev = json.loads(line)
                            if ev.get("verdict") in ("BLOCKED", "DENY"):
                                total_blocked += 1
                        except Exception:
                            pass
        except Exception:
            pass

    # Baseline calculations
    tokens_saved_per_block = 350_000
    cost_per_million_tokens = 6.00
    total_tokens_saved = max(total_blocked * tokens_saved_per_block, total_evals * 15_000)
    estimated_usd_saved = round((total_tokens_saved / 1_000_000) * cost_per_million_tokens, 2)
    dev_hours_saved = round(total_blocked * 0.4 + (total_evals * 0.005), 1)

    return {
        "total_evaluations": total_evals,
        "threats_and_loops_neutralized": total_blocked,
        "estimated_tokens_saved": total_tokens_saved,
        "estimated_usd_saved": estimated_usd_saved,
        "developer_hours_saved": dev_hours_saved
    }


def generate_collaboration_mesh(root_path: str = ".") -> Dict[str, Any]:
    """
    Generates a full cross-extension collaboration matrix and stores
    it in .btp/collaborate.json for IDEs, extensions, and AI agents.
    """
    root = Path(root_path).resolve()
    btp_dir = root / ".btp"
    btp_dir.mkdir(parents=True, exist_ok=True)

    stack = detect_workspace_stack(str(root))
    savings = calculate_savings_telemetry(str(root))

    matrix = []
    for key, archetype in ECOSYSTEM_ARCHETYPES.items():
        matrix.append({
            "archetype_id": key,
            "category": archetype["name"],
            "representatives": archetype["examples"],
            "pain_point": archetype["primary_bottleneck"],
            "solution": archetype["bartholomew_collaboration"],
            "value_roi": archetype["cost_savings"],
            "status": "PROTECTED_BY_BARTHOLOMEW"
        })

    result = {
        "protocol": "BTP Collaboration Protocol v5.4",
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "workspace": stack,
        "savings_telemetry": savings,
        "ecosystem_matrix": matrix,
        "public_api": {
            "node_module": "btp-guard",
            "python_package": "btp-guard",
            "vscode_extension": "Bartholomew.bartholomew-guard-vscode",
            "mcp_server": "btp-guard mcp serve",
            "exported_methods": [
                "is_command_safe(command: str) -> dict",
                "validate_ast(file_path: str, code: str) -> dict",
                "get_proof_telemetry() -> dict",
                "export_model_context() -> str"
            ]
        }
    }

    collaborate_file = btp_dir / "collaborate.json"
    with open(collaborate_file, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2)

    return result


